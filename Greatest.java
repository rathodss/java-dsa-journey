public class Greatest {
    public static void main(String args[]) {
        int x = 25;
        int y = 10;
        int z = 12;
        if (x > y && x > z) {
            System.out.println("Greatest number is X : " + x);
        } else if (y > z) {
            System.out.println("Greatest number is y : " + y);
        } else
            System.out.println("Greatest number is z : " + z);

    }

}
